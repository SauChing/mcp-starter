// Realistic candle generator for timeframes
export function generateCandles(basePrice: number, timeframe: Timeframe, trendBias: number = 0.02): Candle[] {
  const count = timeframe === '1D' ? 48 : timeframe === '5D' ? 60 : timeframe === '1M' ? 30 : timeframe === '6M' ? 50 : 60;
  const now = Date.now();
  const stepMs = timeframe === '1D' ? 15 * 60 * 1000 : timeframe === '5D' ? 2 * 3600 * 1000 : timeframe === '1M' ? 24 * 3600 * 1000 : 7 * 24 * 3600 * 1000;
  
  const candles: Candle[] = [];
  let currentClose = basePrice * (1 - trendBias * 0.8);
  const volatility = basePrice * (timeframe === '1D' ? 0.004 : timeframe === '5D' ? 0.008 : 0.015);

  for (let i = count - 1; i >= 0; i--) {
    const timestamp = now - i * stepMs;
    const dateObj = new Date(timestamp);
    const timeStr = timeframe === '1D' 
      ? dateObj.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' }) 
      : `${dateObj.getMonth() + 1}/${dateObj.getDate()}`;
    
    const delta = (Math.random() - 0.48) * volatility + (trendBias * basePrice / count);
    const open = currentClose;
    const close = Math.max(open + delta, basePrice * 0.5);
    const high = Math.max(open, close) + Math.random() * volatility * 0.8;
    const low = Math.min(open, close) - Math.random() * volatility * 0.8;
    const volume = Math.floor(Math.random() * 500000 + 100000);

    candles.push({
      time: timeStr,
      timestamp,
      open: Number(open.toFixed(2)),
      high: Number(high.toFixed(2)),
      low: Number(low.toFixed(2)),
      close: Number(close.toFixed(2)),
      volume,
    });
    currentClose = close;
  }
  // Anchor last candle close to basePrice
  if (candles.length > 0) {
    candles[candles.length - 1].close = basePrice;
  }
  return candles;
}

